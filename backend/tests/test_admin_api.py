def test_review_queue_requires_admin(client, db_session):
    _problem(db_session)
    response = client.get("/api/admin/review")
    assert response.status_code == 401


def test_non_admin_is_forbidden(client, db_session):
    user = User(github_id=2, username="student")
    db_session.add(user)
    db_session.commit()
    app.dependency_overrides[get_current_user] = lambda: user
    try:
        assert client.get("/api/admin/review").status_code == 403
    finally:
        app.dependency_overrides.pop(get_current_user, None)


def test_review_queue_and_moderation(client, db_session, admin):
    problem = _problem(db_session)
    response = client.get("/api/admin/review")
    assert response.status_code == 200
    body = response.json()
    assert body["total"] == 1
    item = body["items"][0]
    assert item["source_id"] == "SIH26001"
    assert item["extraction_confidence"] == 0.82
    assert item["review_notes"] == "needs a human look"
    assert item["source_url"].startswith("https://sih.gov.in/")

    approved = client.post(f"/api/admin/problems/{problem.id}/approve")
    assert approved.status_code == 200
    assert approved.json()["status"] == "published"
    db_session.refresh(problem)
    assert problem.review_notes.startswith("approved by admin")

    rejected = client.post(f"/api/admin/problems/{problem.id}/reject")
    assert rejected.json()["status"] == "rejected"

    removed = client.post(f"/api/admin/problems/{problem.id}/unpublish")
    assert removed.json()["status"] == "removed"


def test_edit_marks_human_edit(client, db_session, admin):
    problem = _problem(db_session)
    response = client.patch(
        f"/api/admin/problems/{problem.id}",
        json={"title": "Human edited title", "tech_tags": ["Python", "GIS"]},
    )
    assert response.status_code == 200
    db_session.refresh(problem)
    assert problem.title == "Human edited title"
    assert problem.tech_tags == ["python", "gis"]
    assert problem.review_notes.startswith("human edit by admin")


def test_crawl_runs_and_source_takedown(client, db_session, admin):
    problem = _problem(db_session, status="published")
    db_session.add(
        CrawlRun(
            source_key="sih",
            status="success",
            counts={"new": 3, "failed": 0},
            llm_calls=3,
            triggered_by="manual",
        )
    )
    db_session.commit()

    runs = client.get("/api/admin/crawl-runs")
    assert runs.status_code == 200
    assert runs.json()[0]["counts"]["new"] == 3
    run_id = runs.json()[0]["id"]
    assert client.get(f"/api/admin/crawl-runs/{run_id}").status_code == 200

    takedown = client.post("/api/admin/sources/sih/unpublish-all")
    assert takedown.status_code == 200
    assert takedown.json()["unpublished"] == 1
    db_session.refresh(problem)
    assert problem.status == "removed"


